// Command gen reads the pinned DefectDojo OpenAPI document and emits
// internal/registry/registry_gen.go: a Go slice of registry.OperationEntry,
// one per operationId. Parameter/request-body/response schemas are embedded
// as canonical JSON (decoded then re-marshaled with sorted keys, compact
// separators, HTML-escaping disabled) rather than copied verbatim, so the
// output is independent of incidental whitespace/formatting in the source
// document and reproducible across encoders.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type openAPIDoc struct {
	Paths map[string]map[string]json.RawMessage `json:"paths"`
}

type operationSkeleton struct {
	OperationID string          `json:"operationId"`
	Summary     string          `json:"summary"`
	Tags        []string        `json:"tags"`
	Parameters  json.RawMessage `json:"parameters"`
	RequestBody json.RawMessage `json:"requestBody"`
	Responses   json.RawMessage `json:"responses"`
}

type entry struct {
	OperationID string
	Method      string
	Path        string
	Tag         string
	Summary     string
	Parameters  string
	RequestBody string
	Responses   string
}

var httpMethods = map[string]bool{
	"get": true, "post": true, "put": true, "patch": true,
	"delete": true, "head": true, "options": true,
}

func main() {
	if len(os.Args) != 3 {
		log.Fatalf("usage: gen <schema.json> <out.go>")
	}
	schemaPath, outPath := os.Args[1], os.Args[2]

	data, err := os.ReadFile(schemaPath)
	if err != nil {
		log.Fatalf("read schema: %v", err)
	}

	var doc openAPIDoc
	if err := json.Unmarshal(data, &doc); err != nil {
		log.Fatalf("parse schema: %v", err)
	}

	entries := extractEntries(doc)

	if err := os.MkdirAll(filepath.Dir(outPath), 0o755); err != nil {
		log.Fatalf("mkdir: %v", err)
	}
	if err := os.WriteFile(outPath, []byte(render(entries)), 0o644); err != nil {
		log.Fatalf("write %s: %v", outPath, err)
	}
}

func extractEntries(doc openAPIDoc) []entry {
	var entries []entry
	for path, methods := range doc.Paths {
		for method, raw := range methods {
			lm := strings.ToLower(method)
			if !httpMethods[lm] {
				continue
			}

			var op operationSkeleton
			if err := json.Unmarshal(raw, &op); err != nil {
				log.Fatalf("parse operation %s %s: %v", method, path, err)
			}
			if op.OperationID == "" {
				continue
			}

			tag := ""
			if len(op.Tags) > 0 {
				tag = op.Tags[0]
			}

			entries = append(entries, entry{
				OperationID: op.OperationID,
				Method:      strings.ToUpper(method),
				Path:        path,
				Tag:         tag,
				Summary:     op.Summary,
				Parameters:  canonicalize(op.Parameters),
				RequestBody: canonicalize(op.RequestBody),
				Responses:   canonicalize(op.Responses),
			})
		}
	}

	sort.Slice(entries, func(i, j int) bool { return entries[i].OperationID < entries[j].OperationID })
	return entries
}

// canonicalize decodes raw (if present) and re-encodes it with sorted object
// keys, compact separators, and HTML-escaping disabled, so the embedded
// schema text is a deterministic function of the JSON value alone.
func canonicalize(raw json.RawMessage) string {
	if len(raw) == 0 {
		return "null"
	}

	var v interface{}
	if err := json.Unmarshal(raw, &v); err != nil {
		log.Fatalf("canonicalize: %v", err)
	}

	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(v); err != nil {
		log.Fatalf("canonicalize encode: %v", err)
	}

	return strings.TrimSuffix(buf.String(), "\n")
}

func render(entries []entry) string {
	var b strings.Builder
	b.WriteString("// Code generated by internal/registry/gen from openapi/defectdojo-schema.v3.2.100.json. DO NOT EDIT.\n\n")
	b.WriteString("package registry\n\nimport \"encoding/json\"\n\nvar Operations = []OperationEntry{\n")

	for _, e := range entries {
		fmt.Fprintf(&b, "\t{\n")
		fmt.Fprintf(&b, "\t\tOperationID:       %q,\n", e.OperationID)
		fmt.Fprintf(&b, "\t\tMethod:            %q,\n", e.Method)
		fmt.Fprintf(&b, "\t\tPath:              %q,\n", e.Path)
		fmt.Fprintf(&b, "\t\tTag:               %q,\n", e.Tag)
		fmt.Fprintf(&b, "\t\tSummary:           %q,\n", e.Summary)
		fmt.Fprintf(&b, "\t\tParameters:        json.RawMessage(%s),\n", asGoLiteral(e.Parameters))
		fmt.Fprintf(&b, "\t\tRequestBodySchema: json.RawMessage(%s),\n", asGoLiteral(e.RequestBody))
		fmt.Fprintf(&b, "\t\tResponseSchema:    json.RawMessage(%s),\n", asGoLiteral(e.Responses))
		fmt.Fprintf(&b, "\t},\n")
	}

	b.WriteString("}\n")
	return b.String()
}

func asGoLiteral(jsonText string) string {
	if !strings.Contains(jsonText, "`") {
		return "`" + jsonText + "`"
	}
	return fmt.Sprintf("%q", jsonText)
}
